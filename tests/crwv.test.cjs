const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const csv = fs.readFileSync(path.join(root, 'trade_history.csv'), 'utf8');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data.json'), 'utf8'));
const parser = html.slice(html.indexOf('  const tradeIcons'), html.indexOf('  function renderRealizedProfit'));
const parse = source => vm.runInNewContext(source + '\nparseTradeHistory', {});
const before = parse(parser.replace('CRCL CRWV CXMT', 'CRCL CXMT'))(csv);
const after = parse(parser)(csv);
const total = items => items.reduce((sum, item) => sum + item.cents, 0);
assert.equal(total(after), total(before), '分类变化不能增加已实现收益总额');
const crwv = after.filter(item => item.symbol === 'CRWV');
assert.equal(crwv.length, 1);
assert.equal(crwv[0].cents, 10320);
assert.equal(crwv[0].logo, 'asset/CRWV.svg');
assert.equal(before.find(item => item.symbol === '其他').cents - after.find(item => item.symbol === '其他').cents, 10320);
assert.equal(total(parse(parser)(csv)), total(after), '重复加载不能累加收益');
const validation = html.slice(html.indexOf('  function validate(d)'), html.indexOf('  function logo(a)'));
const validate = vm.runInNewContext('const finite = Number.isFinite;\n' + validation + '\nvalidate');
validate(data);
const duplicate = structuredClone(data);
duplicate.holdings.push({...duplicate.holdings.find(item => item.symbol === 'CRWV'), symbol: 'crwv'});
assert.throws(() => validate(duplicate), /重复持仓/);
duplicate.holdings.at(-1).direction = 'short';
validate(duplicate);
console.log(`PASS: CRWV realized 103.20 USDT; portfolio total unchanged (${(total(after)/100).toFixed(2)} USDT); duplicate holdings rejected.`);
